import "server-only";
import { mkdir } from "node:fs/promises";
import path from "node:path";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import * as schema from "./schema";

// The one database connection for the server.
//
// - DATABASE_URL set (production, or a real Postgres locally): postgres.js over that URL. On
//   Supabase it is the pooled connection (Supavisor, transaction mode, port 6543), which cannot use
//   named prepared statements, hence `prepare: false`.
// - No DATABASE_URL outside production: PGlite (Postgres compiled to WebAssembly) persisted in
//   data/dev-db, with the migrations in drizzle/ applied on start, so `npm run dev` needs no setup.
// - No DATABASE_URL in production: DatabaseNotConfiguredError (fail closed); the APIs answer 503.
//
// The connection lives on globalThis so dev hot reloads (and tests that reset modules) reuse it
// instead of opening the same PGlite directory twice.

export type Db = PgDatabase<PgQueryResultHKT, typeof schema>;

/** Production without DATABASE_URL: the message names the setting, never a value. */
export class DatabaseNotConfiguredError extends Error {
  constructor() {
    super("The database is not configured. Set DATABASE_URL (the pooled Postgres connection string).");
    this.name = "DatabaseNotConfiguredError";
  }
}

type Holder = { db?: Promise<Db> };
const holder: Holder = ((globalThis as Record<symbol, unknown>)[Symbol.for("paint-saathi.db")] ??= {}) as Holder;

/** The SQL migrations generated by drizzle-kit (npm run db:generate). */
export const MIGRATIONS_FOLDER = path.join(process.cwd(), "drizzle");

/** The database, connected on first use. A failed connection is retried on the next call. */
export function getDb(): Promise<Db> {
  holder.db ??= connect().catch((err: unknown) => {
    holder.db = undefined;
    throw err;
  });
  return holder.db;
}

async function connect(): Promise<Db> {
  const url = process.env.DATABASE_URL?.trim();
  if (url) return connectPostgres(url);
  if (process.env.NODE_ENV === "production") throw new DatabaseNotConfiguredError();
  // Tests get their own in-memory database (tests/support/db.ts) and must never open this one.
  if (process.env.VITEST) throw new Error("No test database: call useTestDb() from tests/support/db.ts in this test file.");
  return (await openPglite(path.join(process.cwd(), "data", "dev-db"))).db;
}

async function connectPostgres(url: string): Promise<Db> {
  const [{ default: postgres }, { drizzle }] = await Promise.all([import("postgres"), import("drizzle-orm/postgres-js")]);
  const client = postgres(url, { prepare: false, max: 5, idle_timeout: 20, connect_timeout: 10 });
  return drizzle(client, { schema }) as unknown as Db;
}

/**
 * A PGlite database with every migration applied: persisted in `dataDir`, or in memory without
 * one (tests). Used for local development and by the test helper.
 */
export async function openPglite(dataDir?: string): Promise<{ db: Db; close: () => Promise<void> }> {
  const [{ PGlite }, { drizzle }, { migrate }] = await Promise.all([
    import("@electric-sql/pglite"),
    import("drizzle-orm/pglite"),
    import("drizzle-orm/pglite/migrator"),
  ]);
  if (dataDir) await mkdir(dataDir, { recursive: true });
  const client = new PGlite(dataDir);
  const db = drizzle(client, { schema });
  await migrate(db, { migrationsFolder: MIGRATIONS_FOLDER });
  return { db: db as unknown as Db, close: () => client.close() };
}

/** Tests only: use this database (or, with null, forget it so the next getDb connects afresh). */
export function setDb(db: Db | null) {
  holder.db = db ? Promise.resolve(db) : undefined;
}
